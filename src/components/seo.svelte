<script lang="ts">
  import { page } from '$app/stores';
  import { VIDEO_EXTENSIONS } from '$lib/constants';
  import { t } from '$lib/i18n';
  import {
    buildPageGraph,
    jsonLdScriptTag,
    organizationFromConfiguration,
    partsFromStory,
    resolveCanonical,
    validateGraph,
    type StorySchemaParts
  } from '$lib/seo';
  import { dev } from '$app/environment';
  import { getImageAttributes } from '$lib/utils/cms';
  import { getFileExtension } from '$lib/utils/strings';
  import type { AssetStoryblok } from '$types/bloks';
  import { getContext } from 'svelte';

  export let title: undefined | string = undefined;
  export let description: undefined | string = undefined;
  export let image: undefined | AssetStoryblok | string = undefined;
  /**
   * Extra JSON-LD from the Storyblok `structure_data_markup` field. Only
   * FAQPage, HowTo, Service and ItemList nodes are kept (see src/lib/seo/README.md).
   */
  export let structureDataMarkup: string | undefined = undefined;
  /**
   * Schema data for this page. Defaults to what can be derived from the
   * current story. Pass `{ entity: { kind: 'none' } }` for error and private pages.
   */
  export let schema: StorySchemaParts | undefined = undefined;
  export let twitterExtraFields: { key: string; value: string }[] = [];
  export let noIndex: boolean = false;

  const inDrawer = getContext<boolean>('drawer');

  $: story = $page.data.page?.story ?? $page.data.story;
  $: resolvedTitle = title || story?.content?.seo_title || t('seo.title');
  $: resolvedDescription = description || story?.content?.seo_description || t('seo.description');
  $: parts = schema ?? (story?.content ? partsFromStory(story) : undefined);
  // FYI: the seo_canonical_url field only exists on 'Page' | 'Landing Page' | 'Blog Post' | 'Handbook'
  $: canonical = resolveCanonical(
    $page.url.pathname,
    parts?.canonicalOverride ?? story?.content?.seo_canonical_url
  );
  $: graph = inDrawer
    ? undefined
    : buildPageGraph({
        ...(parts ?? { entity: { kind: 'page', institutional: false } }),
        url: canonical,
        title: resolvedTitle,
        description: resolvedDescription,
        manual: structureDataMarkup ?? parts?.manual,
        organization: organizationFromConfiguration($page.data.configuration?.content)
      });
  $: if (dev && graph) {
    const problems = validateGraph(graph);
    if (problems.length) console.warn(`[seo] JSON-LD problems on ${canonical}:`, problems);
  }
  $: jsonLd = graph ? jsonLdScriptTag(graph) : '';
</script>

<svelte:head>
  {#if !inDrawer}
    <link rel="canonical" href={canonical} />
    {#if noIndex}
      <meta name="robots" content="noindex, nofollow" />
    {/if}

    <title>{resolvedTitle}</title>
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:site" content="@SignificaDotCo" />

    <!-- Generated by src/lib/seo. Serialised with <, > and & escaped. -->
    <!-- eslint-disable-next-line svelte/no-at-html-tags -->
    {@html jsonLd}

    <meta name="description" content={resolvedDescription} />
    <meta property="og:title" content={resolvedTitle} />
    <meta property="twitter:title" content={resolvedTitle} />
    <meta property="og:description" content={resolvedDescription} />
    <meta property="twitter:description" content={resolvedDescription} />

    {#each twitterExtraFields as { key, value }, i}
      <meta name="twitter:label{i + 1}" content={key} />
      <meta name="twitter:data{i + 1}" content={value} />
    {/each}

    <meta property="og:url" content={canonical} />
    <meta property="og:type" content="website" />
    {#if typeof image !== 'string' && image?.filename && !VIDEO_EXTENSIONS.includes(getFileExtension(image.filename))}
      {@const { src } = getImageAttributes(image, { size: [1200, 630] })}
      <meta property="og:image" content={src} />
      <meta property="twitter:image" content={src} />
    {:else if story?.content?.seo_og_image?.filename}
      {@const { src } = getImageAttributes(story.content.seo_og_image, {
        size: [1200, 630]
      })}
      <meta property="og:image" content={src} />
      <meta property="twitter:image" content={src} />
    {:else if typeof image === 'string'}
      <meta property="og:image" content={image} />
      <meta property="twitter:image" content={image} />
    {:else}
      <meta property="og:image" content="{$page.url.origin}/og.png" />
      <meta property="twitter:image" content="{$page.url.origin}/og.png" />
    {/if}
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
  {/if}
</svelte:head>
